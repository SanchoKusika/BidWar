-- Что случилось с платной карточкой за последние сутки: на сколько сдвинулась
-- позиция и на сколько изменилась ставка. Обе стрелки в дизайн-ките
-- (`RankBadge.delta` и `StatBlock.delta`) читают отсюда.
--
-- Таблицы-снапшота под это нет и не заводится. Позиция нигде не хранится, она
-- вычисляется на лету (01 Механики), и «где он был вчера» вычисляется так же —
-- из леджера: `paid_amount` сутки назад = текущая ставка минус всё, что
-- `stake_transactions` записала за окно. Тот же принцип, по которому считается
-- коэффициент хейрката: ничего не хранится сверх исходного леджера, и второе
-- состояние не может разъехаться с первым.
--
-- Реконструкция точна, потому что `apply_payment` — единственное место в
-- системе, двигающее очки, и каждое её движение пишет строку в леджер. Знак
-- при этом уже правильный: `attack_out` лежит отрицательным, поэтому
-- полученная атака уменьшает движение, а не увеличивает его.
--
-- Окно скользящее, как у лимитов атак и суточного борда: календарные сутки
-- сделали бы разрыв в полночь на ровном месте.
--
-- Только платный топ: у бесплатного метрика — голоса, а `vote_transactions`
-- пустая до среза 1.7. Появится Vote — здесь добавится второй, симметричный
-- блок, а не переписывание этого.
--
-- ## Две границы точности, обе осознанные
--
-- 1. Проекты моложе суток исключены целиком — и из рангов, и из денег. Сутки
--    назад их в топе не было, «изменение» требует того, что менялось, а рост
--    с нуля до первой ставки это не изменение, а появление. Строки в вьюхе у
--    них нет, и клиент не рисует ни одной стрелки.
-- 2. Скрытые проекты (`status <> 'active'`) не участвуют в прошлом ранге,
--    хотя сутки назад могли стоять в топе. Скрытие — единственное, что меняет
--    позиции соседей мимо леджера; оно редкое и необратимое, а точный учёт
--    потребовал бы как раз той истории, которой мы не держим.
create or replace view paid_movement_24h as
with moved as (
  select
    p.id,
    p.category_id,
    p.paid_amount,
    coalesce((
      select sum(st.amount)
        from stake_transactions st
       where st.project_id = p.id
         and st.created_at > now() - interval '24 hours'
    ), 0)::bigint as amount_delta
  from projects p
  where p.type = 'paid'
    and p.status = 'active'
    and p.created_at <= now() - interval '24 hours'
)
select
  id as project_id,
  amount_delta,
  -- Тай-брейк тот же, что у витрины (01 Механики): metric desc, id asc. Другой
  -- порядок дал бы «изменение» там, где ставки равны и ничего не двигалось.
  row_number() over (order by paid_amount - amount_delta desc, id asc) as past_rank,
  -- Внутри категории — свой ранг: при открытом фильтре на карточке стоит
  -- позиция 1..N этой категории, и вычитать из неё глобальную нельзя.
  row_number() over (
    partition by category_id order by paid_amount - amount_delta desc, id asc
  ) as past_category_rank
from moved;

grant select on paid_movement_24h to anon, authenticated;
