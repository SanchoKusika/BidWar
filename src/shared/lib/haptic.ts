import { getPlatform } from '@/shared/platform';
import { getSettings } from '@/shared/settings';

/**
 * Тактильный отклик на действие, которое уже случилось.
 *
 * Обёртка, а не прямой вызов `platform.haptic()`, ровно по одной причине: у
 * отклика есть настройка, и проверять её в каждом месте вызова — это ждать, что
 * однажды кто-нибудь забудет. Выключенная вибрация здесь не доходит до
 * платформы вовсе.
 *
 * Зовётся только по факту: «платёж применён», «голос отдан», «отказ». На нажатие
 * кнопки, за которой ещё ничего не произошло, отклика нет — иначе он перестаёт
 * что-либо значить.
 */
export function haptic(kind: 'light' | 'medium' | 'heavy' | 'success' | 'error'): void {
  if (!getSettings().haptics) return;
  getPlatform().haptic(kind);
}
